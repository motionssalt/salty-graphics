package com.motionssalt.saltygraphics.ui.editor

import androidx.compose.runtime.Composable
import com.motionssalt.saltygraphics.engine.action.ActionIdentity
import com.motionssalt.saltygraphics.engine.effect.ControlDefinition
import com.motionssalt.saltygraphics.engine.effect.EffectInstance
import com.motionssalt.saltygraphics.engine.model.Layer
import com.motionssalt.saltygraphics.uikit.sublibs.effects.SaltyEffectControlRow
import com.motionssalt.saltygraphics.uikit.sublibs.effects.SaltyEffectsPage

@Composable
fun EffectSettingsSheet(
    targetLayer: Layer,
    allLayers: List<Layer>,
    onAddEffect: (EffectInstance) -> Unit,
    onRemoveEffect: (String) -> Unit,
    onUpdateEffect: (ActionIdentity, EffectInstance) -> Unit,
    onClose: () -> Unit,
    includeDebugEffects: Boolean = false,
    wrapInPanelPage: Boolean = false
) {
    SaltyEffectsPage(
        targetLayer = targetLayer,
        allLayers = allLayers,
        includeDebugEffects = includeDebugEffects,
        onAddEffect = onAddEffect,
        onRemoveEffect = onRemoveEffect,
        onUpdateEffect = onUpdateEffect,
        onClose = onClose,
        wrapInPanelPage = wrapInPanelPage
    )
}

@Composable
fun EffectSettingsSheet(
    targetLayer: Layer,
    allLayers: List<Layer>,
    onAddEffect: (EffectInstance) -> Unit,
    onRemoveEffect: (String) -> Unit,
    onUpdateEffect: (EffectInstance) -> Unit,
    onClose: () -> Unit
) {
    SaltyEffectsPage(
        targetLayer = targetLayer,
        allLayers = allLayers,
        includeDebugEffects = false,
        onAddEffect = onAddEffect,
        onRemoveEffect = onRemoveEffect,
        onUpdateEffect = { _, instance -> onUpdateEffect(instance) },
        onClose = onClose,
        wrapInPanelPage = false
    )
}

@Composable
fun AutoGeneratedControl(
    control: ControlDefinition,
    instance: EffectInstance,
    allLayers: List<Layer>,
    effectName: String = "Effect",
    onOpenColorPicker: (() -> Unit)? = null,
    onValueChange: (ActionIdentity, EffectInstance) -> Unit
) {
    SaltyEffectControlRow(
        control = control,
        instance = instance,
        effectName = effectName,
        allLayers = allLayers,
        onValueChange = onValueChange,
        onOpenColorPicker = onOpenColorPicker
    )
}
